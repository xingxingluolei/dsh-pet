'use strict';
const assert = require('assert');
const { createState } = require('../backend/state');
let now = 1000;
const state = createState({ now: () => now });
state.updateSession('a', 'thinking', 'TaskStarted', { cwd:'/tmp/a', sessionTitle:'任务 A' });
assert.equal(state.snapshot().state, 'thinking');
state.updateSession('a', 'working', 'PreToolUse', { toolName:'Bash' });
state.updateSession('b', 'notification', 'Notification', { sessionTitle:'授权' });
assert.equal(state.snapshot().state, 'waiting');
assert.equal(state.snapshot().current.id, 'b');
state.updateSession('b', 'idle', 'TurnAborted');
assert.equal(state.snapshot().state, 'working');
state.updateSession('a', 'attention', 'Stop', {assistantLastOutput:'完成'});
assert.equal(state.snapshot().state, 'done');
now += 16000;
assert.equal(state.snapshot().state, 'idle');
assert.equal(state.snapshot().sessions.find(s=>s.id==='a').state,'done');
state.updateSession('a','thinking','TaskStarted');
assert.equal(state.snapshot().current.output,'');
assert.equal(state.snapshot().current.tool,'');
state.updateSession('a','idle','TurnAborted');
assert.equal(state.snapshot().current.status,'已中断');
state.updateSession('a','error','ApiError');
assert.equal(state.snapshot().state,'error');
now += 65*60*1000;
assert.equal(state.snapshot().sessions.length,0,'stale sessions must not pretend to still be running');
console.log('state: priority, completion, turn reset, interruption and stale state passed');
